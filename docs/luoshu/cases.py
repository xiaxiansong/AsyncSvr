#   - 入口：双击导航条。桌面双击 → 无屏伴随；应用中双击 → 小屏伴随
#   - 无屏伴随：有动效，导航条变色提醒用户；桌面上只能是无屏伴随
#   - 小屏伴随：让出部分显示区域，含【识别屏幕】按钮、【点击/按住说话】按钮、【叉号】退出按钮；识别屏幕后出现与屏幕内容相关的推荐问题气泡；点击气泡即以气泡内容提问并进入大屏伴随
#   - 大屏伴随：占据约一半屏幕；说话按钮变大并多出键盘图标（可打字）；中间显示 AI 回复；识别屏幕后仍出现气泡；另有【禁止外放】按钮和【伴随记录】按钮
#   - 应用中可通过拖动调整伴随区域大小，在无屏/小屏/大屏之间切换
#   - 伴随中从桌面打开应用 → 自动变为小屏伴随；从应用回到桌面 → 自动变为无屏伴随
#   - 部分折叠形态不能进入伴随（如三折叠完全折叠成单屏时），双折叠折叠态外屏可以进入。这些需要逐形态测试
